#!/usr/bin/env node
// Generates web/src/styles/dither.css: the "Clean" dither layer of Ink & Dither.
// Tiles are tiny ordered-dither SVGs (2 px cells, Bayer 4×4), one set per theme,
// inlined as data URIs so the app stays offline and needs no images.
//   node tools/dither/build-css.mjs
import { writeFileSync } from 'node:fs';

const B4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]].map(r => r.map(v => (v + 0.5) / 16));
const CELL = 2;

/** SVG tile, wc × hc cells; a cell is filled when coverage(x, y) beats its Bayer threshold. */
function tile(wc, hc, color, cov) {
  let rects = '';
  for (let y = 0; y < hc; y++) for (let x = 0; x < wc; x++) {
    if (cov(x, y) > B4[y % 4][x % 4]) rects += `<rect x='${x * CELL}' y='${y * CELL}' width='${CELL}' height='${CELL}'/>`;
  }
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${wc * CELL}' height='${hc * CELL}' shape-rendering='crispEdges' fill='${color}'>${rects}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, '%27')}")`;
}

function vars(shadow, edge) {
  return [
    `  --dt-shadow: ${tile(2, 2, shadow, () => 0.5)};`,                                 // 50% checker
    `  --dt-fade: ${tile(4, 3, shadow, (x, y) => [0.5, 0.25, 0.08][y])};`,                 // under a section line
    `  --dt-fade-up: ${tile(4, 3, shadow, (x, y) => [0.08, 0.25, 0.5][y])};`,              // above the tab bar
    `  --dt-edge: ${tile(4, 3, edge, (x, y) => [0.15, 0.35, 0.6][y])};`,                   // above a sheet
  ].join('\n');
}

// dark: salmon shadows (they read as a lit edge on plum grey), near-black sheet edge
const DARK = vars('#fcd0af', '#060409');
// light: navy shadows and edge on salmon paper
const LIGHT = vars('#1e2152', '#1e2152');

const css = `/* ==========================================================================
   Ink & Dither — the "Clean" dither layer. GENERATED by tools/dither/build-css.mjs;
   edit that file, not this one.
   Three effects, kept quiet on purpose:
   1. a small ordered-dither drop shadow just outside the bottom-right of buttons
      and boxes (it shrinks when pressed);
   2. a short dither fade under section lines, above the tab bar and above sheets,
      so layers separate without a flat grey;
   3. the same shadow under the active tab's box.
   ========================================================================== */
:root {
${DARK}
  --dt-off: 3px;
}
:root[data-theme='light'] {
${LIGHT}
}
@media (prefers-color-scheme: light) {
  :root[data-theme='system'] {
${LIGHT.replace(/^ {2}/gm, '    ')}
  }
}

/* ---------- 1. dither drop shadow: an L-shaped strip outside the box ---------- */
:where(.btn:not(.quiet), .lockup, .seg, .verdict.beat, .verdict.hit, .asheet-group) { position: relative; }
:where(.seg, .verdict, .stepper-btn) { --dt-off: 2px; }
.btn:not(.quiet):not(:disabled)::after, .lockup::after, .seg::after, .verdict.beat::after, .verdict.hit::after, .asheet-group::after {
  content: ''; position: absolute; inset: calc(var(--rule-w) * -1); pointer-events: none;
  transform: translate(var(--dt-off), var(--dt-off));
  background-image: var(--dt-shadow); background-size: 4px 4px; image-rendering: pixelated;
  /* keep only the part that sticks out past the box (right + bottom) */
  clip-path: polygon(calc(100% - var(--dt-off)) 0, 100% 0, 100% 100%, 0 100%, 0 calc(100% - var(--dt-off)), calc(100% - var(--dt-off)) calc(100% - var(--dt-off)));
  transition: transform 160ms ease-out;
}
.btn:not(.quiet):not(:disabled):active::after { transform: translate(1px, 1px); }

/* ---------- 2. dither fades: section lines, tab bar, sheets ---------- */
:where(.tk-hd, .tk-sheet-hd, .lg-spec-hd, .sheetblk-hd, .tpl-hd, .slot-spec, .sess-hd) { position: relative; }
.tk-hd::after, .tk-sheet-hd::after, .lg-spec-hd::after, .sheetblk-hd::after, .tpl-hd::after, .slot-spec::after, .sess-hd::after {
  content: ''; position: absolute; left: 0; right: 0; top: 100%; margin-top: var(--rule-w); height: 6px; pointer-events: none;
  background-image: var(--dt-fade); background-size: 8px 6px; background-repeat: repeat-x; image-rendering: pixelated;
}
.tabbar::before {
  content: ''; position: absolute; left: 0; right: 0; bottom: 100%; margin-bottom: var(--rule-w); height: 6px; pointer-events: none;
  background-image: var(--dt-fade-up); background-size: 8px 6px; background-repeat: repeat-x; image-rendering: pixelated;
}
.sheet::before {
  content: ''; position: absolute; left: 0; right: 0; bottom: 100%; margin-bottom: var(--rule-w); height: 6px; pointer-events: none;
  background-image: var(--dt-edge); background-size: 8px 6px; background-repeat: repeat-x; image-rendering: pixelated;
}

/* ---------- 3. active tab box: the same L-shaped dither shadow ---------- */
.tabbar a.on .tab-box::after {
  content: ''; position: absolute; inset: calc(var(--rule-w) * -1); z-index: -1; pointer-events: none;
  transform: translate(2px, 2px);
  background-image: var(--dt-shadow); background-size: 4px 4px; image-rendering: pixelated;
  clip-path: polygon(calc(100% - 2px) 0, 100% 0, 100% 100%, 0 100%, 0 calc(100% - 2px), calc(100% - 2px) calc(100% - 2px));
}

@media (prefers-reduced-motion: reduce) { .btn::after { transition: none; } }
`;
writeFileSync(new URL('../../web/src/styles/dither.css', import.meta.url), css);
console.log('wrote web/src/styles/dither.css');
